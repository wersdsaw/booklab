export function generateSalaryAndLore(level: HierarchyLevel): { salary: number; lore: LoreProfile } {
  if (level === 'Керівник') {
    const salary = 30000;
    const template = HEAD_LORE;
    const story = template.stories[Math.floor(Math.random() * template.stories.length)];
    const expenses = template.expenses[Math.floor(Math.random() * template.expenses.length)];
    const lifestyle = template.lifestyles[Math.floor(Math.random() * template.lifestyles.length)];
    return {
      salary,
      lore: { salary, story, expenses, lifestyle }
    };
  }

  if (level === 'Тімлід') {
    const salary = 15000;
    const template = TEAM_LEAD_LORE;
    const story = template.stories[Math.floor(Math.random() * template.stories.length)];
    const expenses = template.expenses[Math.floor(Math.random() * template.expenses.length)];
    const lifestyle = template.lifestyles[Math.floor(Math.random() * template.lifestyles.length)];
    return {
      salary,
      lore: { salary, story, expenses, lifestyle }
    };
  }

  // Менеджер: Random salary between 1,000 and 25,000 UAH
  const rawSalary = Math.floor(Math.random() * 24000) + 1000;
  const salary = Math.round(rawSalary / 500) * 500;

  const matchedBracket = MANAGER_LORE_TEMPLATES.find(
    (b) => salary >= b.minSalary && salary <= b.maxSalary
  ) || MANAGER_LORE_TEMPLATES[0];

  const story = matchedBracket.stories[Math.floor(Math.random() * matchedBracket.stories.length)];
  const expenses = matchedBracket.expenses[Math.floor(Math.random() * matchedBracket.expenses.length)];
  const lifestyle = matchedBracket.lifestyles[Math.floor(Math.random() * matchedBracket.lifestyles.length)];

  return {
    salary,
    lore: { salary, story, expenses, lifestyle }
  };
}
